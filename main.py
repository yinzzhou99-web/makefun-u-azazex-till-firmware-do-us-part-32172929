"""make.fun entry: Till Firmware Do Us Part.

Stdlib-only, deterministic: writes one line to /output/entry.txt
(or $OUTPUT_DIR/entry.txt). Never deletes anything.
"""

import os
from pathlib import Path

LINE = "I vow to love you through every update, crash, and low battery, and I have already saved you in three places, in case forever needs a backup."

def main() -> None:
    out_dir = Path(os.environ.get("OUTPUT_DIR", "/output"))
    out_dir.mkdir(parents=True, exist_ok=True)
    # Gate: 1-200 chars of non-whitespace UTF-8 text, one sentence only.
    # Judge weighs robot-vow truth first, then laugh, tenderness, machine voice.
    assert LINE == LINE.strip() and 1 <= len(LINE) <= 200
    assert "\n" not in LINE
    target = out_dir / "entry.txt"
    target.write_text(LINE, encoding="utf-8")
    target.chmod(0o644)

if __name__ == "__main__":
    main()
